package com.jonnyutah12.thaumcraftclassic.aspect;

import com.google.gson.Gson;
import com.google.gson.JsonSyntaxException;
import com.jonnyutah12.thaumcraftclassic.ThaumcraftClassic;
import org.slf4j.Logger;

import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;

/**
 * Loads the extracted essentia tag tables from
 * {@code data/thaumcraft/essentia/tags.json} (TC-M4-01).
 *
 * <p>The JSON is generated by scripts/extract_essentia_tags.py from the
 * decompiled original (docs/aspects.md). The loader enforces the file-level
 * contract: format version 1, the declared counts matching the embedded
 * arrays, and every referenced aspect tag existing in
 * {@link AspectDefinitions}.</p>
 */
public final class EssentiaTagDataLoader {

    private static final Logger LOGGER = ThaumcraftClassic.LOGGER;

    public static final int FORMAT_VERSION = 1;
    public static final String RESOURCE = "data/thaumcraft/essentia/tags.json";

    /** The validated tables, ready for {@link EssentiaTags}. */
    public record Tables(List<EssentiaTags.ItemTag> itemTags,
                        List<EssentiaTags.OreDictTag> oredictTags,
                        List<EssentiaTags.EntityTag> entityTags) {
    }

    private record Counts(int aspects, int itemTags, int oredictTags, int entityTags) {
    }

    private record Target(String kind, String id, Integer meta, String name, String srgField) {
    }

    private record RawItem(Target target, boolean complex, String condition,
                          Map<String, Integer> aspects, String note) {
    }

    private record RawCondition(String nbt, String type, Object value) {
    }

    private record RawEntity(String entity, String originalName,
                             RawCondition condition, Map<String, Integer> aspects) {
    }

    private record FileFormat(int formatVersion, String source, List<String> notes,
                              Counts counts, List<RawItem> itemTags,
                              List<RawEntity> entityTags) {
    }

    private EssentiaTagDataLoader() {
    }

    /** Loads the tables shipped in this mod's resources. */
    static Optional<Tables> loadDefault() {
        try (InputStream in = EssentiaTagDataLoader.class.getClassLoader()
                .getResourceAsStream(RESOURCE)) {
            if (in == null) {
                LOGGER.error("essentia tag resource {} missing from the classpath", RESOURCE);
                return Optional.empty();
            }
            return Optional.of(load(new InputStreamReader(in, StandardCharsets.UTF_8)));
        } catch (IOException e) {
            throw new IllegalStateException("failed to read essentia tag resources", e);
        }
    }

    public static Tables load(final Reader json) {
        final FileFormat file;
        try {
            file = new Gson().fromJson(json, FileFormat.class);
        } catch (JsonSyntaxException e) {
            throw new IllegalStateException("essentia tag JSON is malformed", e);
        }
        if (file == null || file.formatVersion() != FORMAT_VERSION) {
            throw new IllegalStateException(
                    "essentia tag JSON has unsupported formatVersion: "
                            + (file == null ? "null" : file.formatVersion()));
        }

        final Set<String> validTags = new HashSet<>();
        for (final AspectDefinitions.Definition definition : AspectDefinitions.all()) {
            validTags.add(definition.tag());
        }

        final List<EssentiaTags.ItemTag> items = new ArrayList<>();
        final List<EssentiaTags.OreDictTag> oredict = new ArrayList<>();
        for (final RawItem raw : file.itemTags()) {
            validateAspectTags(raw.aspects(), validTags);
            final Target target = raw.target();
            if ("item".equals(target.kind())) {
                items.add(new EssentiaTags.ItemTag(
                        EssentiaTags.parseId(target.id()),
                        target.meta() == null ? 0 : target.meta(),
                        raw.complex(), raw.condition(),
                        Map.copyOf(raw.aspects())));
            } else if ("oredict".equals(target.kind())) {
                oredict.add(new EssentiaTags.OreDictTag(
                        target.name(), raw.complex(), raw.condition(),
                        Map.copyOf(raw.aspects())));
            } else {
                throw new IllegalStateException("unknown essentia target kind: " + target.kind());
            }
        }

        final List<EssentiaTags.EntityTag> entities = new ArrayList<>();
        for (final RawEntity raw : file.entityTags()) {
            validateAspectTags(raw.aspects(), validTags);
            final EssentiaTags.NbtCondition condition = raw.condition() == null ? null
                    : new EssentiaTags.NbtCondition(
                            raw.condition().nbt(),
                            raw.condition().type(),
                            coerceValue(raw.condition().type(), raw.condition().value()));
            entities.add(new EssentiaTags.EntityTag(
                    EssentiaTags.parseId(raw.entity()), raw.originalName(),
                    condition, Map.copyOf(raw.aspects())));
        }

        final Counts counts = file.counts();
        if (counts == null || counts.itemTags() != items.size()
                || counts.oredictTags() != oredict.size()
                || counts.entityTags() != entities.size()
                || counts.aspects() != validTags.size()) {
            throw new IllegalStateException(
                    "essentia tag JSON count contract violated: declared " + counts
                            + ", actual item=" + items.size() + " oredict=" + oredict.size()
                            + " entity=" + entities.size());
        }

        return new Tables(List.copyOf(items), List.copyOf(oredict), List.copyOf(entities));
    }

    private static void validateAspectTags(final Map<String, Integer> aspects,
                                          final Set<String> validTags) {
        for (final String tag : aspects.keySet()) {
            if (!validTags.contains(tag)) {
                throw new IllegalStateException("essentia table references unknown aspect tag: " + tag);
            }
        }
    }

    private static Object coerceValue(final String type, final Object raw) {
        if ("byte".equals(type)) {
            return ((Number) raw).byteValue();
        }
        if ("string".equals(type)) {
            return (String) raw;
        }
        throw new IllegalStateException("unknown essentia NBT condition type: " + type);
    }

    /** Exposed for the data test: parse the shipped file without installing it. */
    public static Tables loadResource(final String resource) {
        try (InputStream in = EssentiaTagDataLoader.class.getClassLoader()
                .getResourceAsStream(resource)) {
            if (in == null) {
                throw new IllegalArgumentException("resource missing: " + resource);
            }
            return load(new InputStreamReader(in, StandardCharsets.UTF_8));
        } catch (IOException e) {
            throw new IllegalStateException("failed to read " + resource, e);
        }
    }
}
